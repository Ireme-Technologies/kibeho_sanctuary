export function navKeyForPath(path) {
  if (!path) return null
  if (NAV_PATH_KEYS[path]) return NAV_PATH_KEYS[path]
  const bare = String(path).split('?')[0]
  return NAV_PATH_KEYS[bare] || null
}

export function resolveNavLabel(item, t, locale, defaultLocale = 'en') {
  const custom = item?.translations?.[locale]?.label
  let label = item?.label || ''
  if (custom && String(custom).trim()) {
    label = String(custom).trim()
  } else if (locale && locale !== defaultLocale) {
    const key = navKeyForPath(item?.path)
    if (key) {
      const translated = t(key)
      if (translated && translated !== key) label = translated
    }
  }
  return displayTitleLabel(label, locale)
}
